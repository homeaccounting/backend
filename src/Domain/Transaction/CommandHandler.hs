-- Handle InitiateTransactionMerge command
--
-- Initiating command for the merge saga (routed to the target/survivor).
-- The service layer has already resolved amounts + synthesised
-- @newTransactionType@; the handler only validates the target is Completed and
-- no saga is already in flight, then emits 'TransactionMergeInitiated' (target
-- is the stream key, so it is not a payload field). The @*InProgress@ flags are
-- only ever True on uncommitted state, so this guard is effectively a defensive
-- re-entrancy check.
handleTransactionCommand transaction (InitiateTransactionMergeTransactionCommand InitiateTransactionMerge {..}) =
  case transaction ^. #status of
    Completed
      | transaction ^. #amendmentInProgress
          || transaction ^. #cancellationInProgress
          || transaction ^. #mergeInProgress ->
          Left MergeAlreadyInProgress
      | otherwise ->
          Right
            [ TransactionMergeInitiatedTransactionEvent
                TransactionMergeInitiated
                  { newSourceAccountId = newSourceAccountId,
                    newTargetAccountId = newTargetAccountId,
                    newSourceAmount = newSourceAmount,
                    newTargetAmount = newTargetAmount,
                    newExchangeRate = newExchangeRate,
                    newAllocations = newAllocations,
                    newTransactionType = newTransactionType,
                    contactId = contactId,
                    sourceTransactionIds = sourceTransactionIds,
                    by = by
                  }
            ]
    _ -> Left CannotEditUncompletedTransaction
-- Handle CompleteTransactionMerge command
--
-- Saga-internal. Accepted iff a merge is in progress.
handleTransactionCommand transaction (CompleteTransactionMergeTransactionCommand CompleteTransactionMerge {..}) =
  if not (transaction ^. #mergeInProgress)
    then Left NoMergeInProgress
    else
      Right
        [ TransactionMergeCompletedTransactionEvent
            TransactionMergeCompleted {by = by}
        ]
-- Handle FailTransactionMerge command
--
-- Saga-internal. Accepted iff a merge is in progress.
handleTransactionCommand transaction (FailTransactionMergeTransactionCommand FailTransactionMerge {..}) =
  if not (transaction ^. #mergeInProgress)
    then Left NoMergeInProgress
    else
      Right
        [ TransactionMergeFailedTransactionEvent
            TransactionMergeFailed {reason = reason}
        ]
-- Handle AddTransactionRelation command
--
-- Post-hoc relation edge (Merge/Split lineage). Completed-only. The self-link
-- check is pure here because the command carries the owning aggregate id.
handleTransactionCommand transaction (AddTransactionRelationTransactionCommand AddTransactionRelation {..})
  | unTransactionId transactionId == unTransactionId relatedTransactionId = Left RelationSelfLink
  | otherwise = case transaction ^. #status of
      Completed ->
        Right
          [ TransactionRelationAddedTransactionEvent
              TransactionRelationAdded
                { relatedTransactionId = relatedTransactionId,
                  relationKind = relationKind
                }
          ]
      _ -> Left CannotEditUncompletedTransaction
-- Handle RemoveTransactionRelation command
--
-- Mirror of 'AddTransactionRelation': Completed-only, self-link check is pure
-- here because the command carries the owning aggregate id. Direction
-- resolution + lineage-kind restriction are enforced at the service layer.
handleTransactionCommand transaction (RemoveTransactionRelationTransactionCommand RemoveTransactionRelation {..})
  | unTransactionId transactionId == unTransactionId relatedTransactionId = Left RelationSelfLink
  | otherwise = case transaction ^. #status of
      Completed ->
        Right
          [ TransactionRelationRemovedTransactionEvent
              TransactionRelationRemoved
                { relatedTransactionId = relatedTransactionId,
                  relationKind = relationKind
                }
          ]
      _ -> Left CannotEditUncompletedTransaction

-- -----------------------------------------------------------------------------
-- Allocation invariants (handler-boundary)
-- -----------------------------------------------------------------------------

-- | Check that an allocation list is consistent with the expected total:
-- currency equality, sum equality, and per-allocation positivity. Used by
-- 'InitiateTransactionPosting', 'ChangeTransactionAllocations', and 'InitiateTransactionAmendment'
-- handler arms as a defensive boundary check (the smart constructors in
-- 'Domain.Transaction.Types' already enforce these — the re-check covers
-- direct constructions bypassing them).
checkAllocationsAgainst :: Money -> Allocations -> Either TransactionError ()
checkAllocationsAgainst expected a =
  checkAllocationsNotEmpty a *> checkAllocationsCurrency (moneyCurrency expected) a *> checkSum *> checkAllocationsPositive a
  where
    checkSum = if Money (allocationsTotal a) (moneyCurrency expected) == expected then Right () else Left AllocationsDoNotSumToTotal

-- | Fee rules for a 'Transfer' (spec §4): expense bucket only, source
-- currency, each fee positive, total strictly below the source amount, and —
-- when no FX conversion is involved — @source - total == target@. Arguments:
-- source, target, fees.
checkTransferFees :: Money -> Money -> Allocations -> Either TransactionError ()
checkTransferFees source target fees =
  checkAllocationsNotEmpty fees
    *> checkNoIncome
    *> checkAllocationsCurrency (moneyCurrency source) fees
    *> checkAllocationsPositive fees
    *> checkBelowSource
    *> checkBalance
  where
    feeTotal = allocationsTotal fees
    checkNoIncome = if null fees.incomes then Right () else Left TransferFeeIncomeNotSupported
    checkBelowSource = if feeTotal < unMoney source then Right () else Left TransferFeesNotBelowSource
    checkBalance
      | moneyCurrency source == moneyCurrency target && unMoney source - feeTotal /= unMoney target = Left TransferFeesDoNotBalance
      | otherwise = Right ()

checkTransferFeesIfAny :: Money -> Money -> Maybe Allocations -> Either TransactionError ()
checkTransferFeesIfAny source target = maybe (Right ()) (checkTransferFees source target)

checkAllocationsNotEmpty :: Allocations -> Either TransactionError ()
checkAllocationsNotEmpty a = if null (allAllocations a) then Left AllocationsEmpty else Right ()

checkAllocationsCurrency :: Currency -> Allocations -> Either TransactionError ()
checkAllocationsCurrency cur a =
  if all (\x -> x.amount.currency == cur) (allAllocations a) then Right () else Left AllocationCurrencyMismatch

checkAllocationsPositive :: Allocations -> Either TransactionError ()
checkAllocationsPositive a =
  if all (\x -> unMoney x.amount > 0) (allAllocations a) then Right () else Left AllocationAmountNotPositive

