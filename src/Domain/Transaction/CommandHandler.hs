-- -----------------------------------------------------------------------------
-- Command Errors
-- -----------------------------------------------------------------------------

-- | Errors that can occur when handling transaction commands.
--
-- These are aggregate-local errors. The service layer translates them into
-- their 'Domain.Core.Errors.DomainError' counterparts before surfacing to
-- the HTTP layer.
data TransactionError
  = TransactionAlreadyInitiated
  | TransactionNotPending
  | TransferToSameAccount
  | TransferAmountNotPositive
  | -- | An edit command (labels, category, description, business date)
    -- was issued against a transaction whose status is not Completed.
    CannotEditUncompletedTransaction
  | -- | 'ChangeTransactionAllocations' issued against a Transfer or Adjustment,
    -- which has no allocations to set.
    CannotSetAllocationsOnUncategorisedTransaction
  | -- | 'ChangeTransactionAllocations' / 'InitiateTransactionAmendment' issued with a
    -- @newTransactionType@ whose kind differs from the existing transaction's.
    CannotChangeKindOfCategorisedTransaction
  | -- | Sum of allocation amounts does not equal the categorised total.
    AllocationsDoNotSumToTotal
  | -- | At least one allocation has a non-positive amount.
    AllocationAmountNotPositive
  | -- | An allocation's currency differs from the categorised side's.
    AllocationCurrencyMismatch
  | -- | An Expense transaction carries a non-empty income bucket —
    -- contra-income is not supported.
    ContraIncomeNotSupported
  | -- | Allocation payload has both buckets empty; at least one allocation
    -- is required on a categorised transaction.
    AllocationsEmpty
  | -- | InitiateTransactionAmendment payload referenced the same account on both legs.
    AmendTransferToSameAccountPair
  | -- | InitiateTransactionAmendment payload carried a zero source or target amount.
    AmendTransferToZeroAmount
  | -- | A transfer fee allocation sits in the income bucket; fees are expenses.
    TransferFeeIncomeNotSupported
  | -- | Transfer fees sum to the debited amount or more.
    TransferFeesNotBelowSource
  | -- | Same-currency transfer where @source - fees /= target@.
    TransferFeesDoNotBalance
  | -- | 'ChangeTransactionAllocations' on a transfer changed the fee total.
    TransferFeeTotalChanged
  | -- | A saga-completion or saga-failure command was issued without
    -- a prior 'TransactionAmendmentInitiated' on the stream.
    NoAmendmentInProgress
  | -- | 'InitiateTransactionCancellation' was issued against a transaction that is already
    -- in the 'Cancelled' state.
    TransactionAlreadyCancelled
  | -- | 'InitiateTransactionCancellation' was issued while a cancellation saga is already
    -- in flight (@cancellationInProgress = True@).
    CancellationAlreadyInProgress
  | -- | 'InitiateTransactionCancellation' was issued while an amendment saga is in flight
    -- (@amendmentInProgress = True@). The amendment must complete or fail
    -- first.
    CannotCancelDuringAmendment
  | -- | 'CompleteTransactionCancellation' was issued when no cancellation is
    -- in progress (@cancellationInProgress = False@).
    NoCancellationInProgress
  | -- | 'InitiateTransactionAmendment' was issued while a cancellation saga is in flight
    -- (@cancellationInProgress = True@).
    CannotAmendDuringCancellation
  | -- | 'InitiateTransactionAmendment' supplied a 'newTransactionType' whose kind is
    --   'Adjustment'. Cross-kind amendment into Adjustment is unsupported.
    CannotAmendToAdjustmentKind
  | -- | 'AddTransactionRelation' referenced the owning transaction as its own
    -- related endpoint (@transactionId == relatedTransactionId@). A transaction
    -- cannot be related to itself.
    RelationSelfLink
  | -- | 'InitiateTransactionMerge' was issued while an amendment, cancellation, or
    -- merge saga is already in flight on the target (@*InProgress = True@).
    MergeAlreadyInProgress
  | -- | 'CompleteTransactionMerge' / 'FailTransactionMerge' was issued when no
    -- merge is in progress (@mergeInProgress = False@).
    NoMergeInProgress
  | -- | 'ReconcileTransactionImport' was issued against a transaction whose
    -- import-attribution capacity is already used up: the attach would push
    -- @attributedExternalIds@ past 'importAttributionCapacity' (one id for an
    -- income/expense, two for a transfer — one per leg).
    TransactionAlreadyReconciled
  deriving (Show, Eq)

-- -----------------------------------------------------------------------------
-- Command Sum Type Construction
-- -----------------------------------------------------------------------------

-- | Generate the TransactionCommand sum type from individual command types.
--
-- This Template Haskell splice creates:
--  data TransactionCommand
--    = InitiateTransactionPostingTransactionCommand InitiateTransactionPosting
--    | CompleteTransactionPostingTransactionCommand CompleteTransactionPosting
--    | FailTransactionPostingTransactionCommand FailTransactionPosting
--
-- Each variant wraps one of the individual command types defined in
-- Domain.Transaction.Commands.
--
-- The sum type enables pattern matching on all possible commands in the
-- handler function.
constructSumType
  "TransactionCommand"
  (withTagOptions AppendTypeNameToTags defaultSumTypeOptions)
  transactionCommands

-- -----------------------------------------------------------------------------
-- Command Handler Function
-- -----------------------------------------------------------------------------

-- | Handle a transaction command and produce events.
--
-- This function implements the business logic for validating commands against
-- the current aggregate state. It is pure and deterministic.
--
-- Command Handling:
--  - InitiateTransactionPosting: Validates accounts differ, amount positive, emits TransactionPostingInitiated
--  - CompleteTransactionPosting: Validates status is Pending, emits TransactionPostingCompleted
--  - FailTransactionPosting: Validates status is Pending, emits TransactionPostingFailed
--
-- Business Rules:
--  1. InitiateTransactionPosting can only be first command (status must not be set)
--  2. Source and target accounts must be different
--  3. Transfer amount must be positive
--  4. CompleteTransactionPosting only works on Pending transactions
--  5. FailTransactionPosting only works on Pending transactions
--  6. Terminal states (Completed/Failed) cannot be modified
--
-- Returns:
--  @'Right' events@ on success, @'Left' error@ on rejection.
--
-- Mathematical Property:
--  handleTransactionCommand is deterministic:
--  ∀ s c. handleTransactionCommand s c == handleTransactionCommand s c
--
-- State Machine Enforcement:
--  Only Pending transactions can transition to Completed or Failed.
handleTransactionCommand :: Transaction -> TransactionCommand -> Either TransactionError [TransactionEvent]
-- Handle InitiateTransactionPosting command
handleTransactionCommand transaction (InitiateTransactionPostingTransactionCommand InitiateTransactionPosting {..}) =
  case transaction ^. #status of
    Pending
      | unMoney transaction.sourceAmount == 0 ->
          if unAccountId sourceAccountId == unAccountId targetAccountId
            then Left TransferToSameAccount
            else
              if unMoney sourceAmount <= 0 || unMoney targetAmount <= 0
                then Left TransferAmountNotPositive
                else do
                  -- Categorised-side checks. Smart constructors should have
                  -- run these, but we re-check defensively at the handler
                  -- boundary because nothing prevents a caller from
                  -- assembling a 'TransactionType' directly.
                  case transactionType of
                    Income allocs -> checkAllocationsAgainst targetAmount allocs
                    Expense allocs ->
                      checkAllocationsAgainst sourceAmount allocs
                        *> (if null allocs.incomes then Right () else Left ContraIncomeNotSupported)
                    Transfer fees -> checkTransferFeesIfAny sourceAmount targetAmount fees
                    Adjustment -> Right ()
                  let postingEvt =
                        TransactionPostingInitiatedTransactionEvent
                          TransactionPostingInitiated
                            { sourceAccountId = sourceAccountId,
                              targetAccountId = targetAccountId,
                              sourceAmount = sourceAmount,
                              targetAmount = targetAmount,
                              exchangeRate = exchangeRate,
                              description = description,
                              by = initiatedBy,
                              at = at,
                              transactionType = transactionType,
                              importInfo = importInfo,
                              labels = labels,
                              contactId = contactId
                            }
                  -- No self-link check here: the freshly-generated aggregate id
                  -- is unknown to the pure handler (a fresh UUID can never equal
                  -- an existing target, so a self-link is structurally
                  -- impossible on the create path). The service is the
                  -- authoritative guard.
                  Right $
                    postingEvt : case relation of
                      Nothing -> []
                      Just spec ->
                        [ TransactionRelationAddedTransactionEvent
                            TransactionRelationAdded
                              { relatedTransactionId = spec.relatedTransactionId,
                                relationKind = spec.relationKind
                              }
                        ]
      | otherwise -> Left TransactionAlreadyInitiated
    _ -> Left TransactionAlreadyInitiated
-- Handle CompleteTransactionPosting command
handleTransactionCommand transaction (CompleteTransactionPostingTransactionCommand CompleteTransactionPosting) =
  case transaction ^. #status of
    Pending -> Right [TransactionPostingCompletedTransactionEvent TransactionPostingCompleted]
    _ -> Left TransactionNotPending
-- Handle FailTransactionPosting command
handleTransactionCommand transaction (FailTransactionPostingTransactionCommand FailTransactionPosting {..}) =
  case transaction ^. #status of
    Pending ->
      Right
        [ TransactionPostingFailedTransactionEvent
            TransactionPostingFailed
              { reason = reason
              }
        ]
    _ -> Left TransactionNotPending
-- Handle SetTransactionLabels command
handleTransactionCommand transaction (SetTransactionLabelsTransactionCommand SetTransactionLabels {..}) =
  case transaction ^. #status of
    Completed ->
      Right
        [ TransactionLabelsSetTransactionEvent
            TransactionLabelsSet
              { transactionId = transactionId,
                labels = labels
              }
        ]
    _ -> Left CannotEditUncompletedTransaction
-- Handle SetTransactionContact command
handleTransactionCommand transaction (SetTransactionContactTransactionCommand SetTransactionContact {..}) =
  case transaction ^. #status of
    Completed ->
      Right
        [ TransactionContactSetTransactionEvent
            TransactionContactSet
              { transactionId = transactionId,
                contactId = contactId
              }
        ]
    _ -> Left CannotEditUncompletedTransaction
-- Handle ReconcileTransactionImport command
--
-- Attaches import attribution onto a completed manual transaction. Balance-neutral —
-- emits a single 'TransactionImportReconciled'. Rejected if the transaction is not
-- Completed, or if the attach would exceed the transaction's
-- 'importAttributionCapacity' (guard against over-attaching).
--
-- Capacity is counted in external ids, not attach events, so the two ways a
-- transfer can be fully attributed agree: one whole-pair attach carrying both
-- legs' ids (0 + 2), or two single-leg attaches (0 + 1, then 1 + 1). Either way
-- a further attach is rejected. An income/expense allows 0 + 1 and then rejects
-- 1 + 1 — exactly the reconcile-once behaviour it had before capacity existed.
handleTransactionCommand transaction (ReconcileTransactionImportTransactionCommand ReconcileTransactionImport {..}) =
  case transaction ^. #status of
    Completed
      | fromIntegral (transaction ^. #attributedExternalIds) + length externalTransactionIds
          > importAttributionCapacity (transaction ^. #transactionType) ->
          Left TransactionAlreadyReconciled
      | otherwise ->
          Right
            [ TransactionImportReconciledTransactionEvent
                TransactionImportReconciled
                  { transactionId = transactionId,
                    externalTransactionIds = externalTransactionIds,
                    category = category,
                    contact = contact
                  }
            ]
    _ -> Left CannotEditUncompletedTransaction
-- Handle ChangeTransactionAllocations command
--
-- The command carries only the new allocation list; the surrounding
-- kind (Income / Expense) is preserved from the existing transaction.
-- Kind preservation is therefore structural — there is no incoming
-- kind to compare with — so we only check that the existing
-- transaction is categorised, then validate the allocations against
-- the existing categorised total / currency / positivity.
handleTransactionCommand transaction (ChangeTransactionAllocationsTransactionCommand ChangeTransactionAllocations {..}) =
  case transaction ^. #status of
    Completed ->
      case allocationsOf (transaction ^. #transactionType) of
        Nothing ->
          Left CannotSetAllocationsOnUncategorisedTransaction
        Just oldAllocations -> do
          case transaction.transactionType of
            Income _ -> checkAllocationsAgainst transaction.targetAmount newAllocations
            Expense _ -> do
              checkAllocationsAgainst transaction.sourceAmount newAllocations
              -- preserve the contra rule: an Expense must not gain an income bucket
              if null newAllocations.incomes then Right () else Left ContraIncomeNotSupported
            Transfer _ -> do
              -- total first: a changed total would otherwise surface as a balance error
              if allocationsTotal newAllocations == allocationsTotal oldAllocations then Right () else Left TransferFeeTotalChanged
              checkTransferFees transaction.sourceAmount transaction.targetAmount newAllocations
            Adjustment -> Left CannotSetAllocationsOnUncategorisedTransaction
          Right
            [ TransactionAllocationsChangedTransactionEvent
                TransactionAllocationsChanged
                  { transactionId = transactionId,
                    newAllocations = newAllocations
                  }
            ]
    _ -> Left CannotEditUncompletedTransaction
-- Handle ChangeTransactionDescription command
handleTransactionCommand transaction (ChangeTransactionDescriptionTransactionCommand ChangeTransactionDescription {..}) =
  case transaction ^. #status of
    Completed ->
      Right
        [ TransactionDescriptionChangedTransactionEvent
            TransactionDescriptionChanged
              { transactionId = transactionId,
                newDescription = newDescription
              }
        ]
    _ -> Left CannotEditUncompletedTransaction
-- Handle ChangeTransactionDate command
handleTransactionCommand transaction (ChangeTransactionDateTransactionCommand ChangeTransactionDate {..}) =
