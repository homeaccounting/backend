-- |
-- Module      : Domain.Transaction.CommandHandler
-- Description : Command handler for the Transaction aggregate
--
-- This module implements the command handler that validates transaction commands
-- against the current aggregate state and emits appropriate events.
--
-- The command handler is the core of the write side in CQRS:
--   1. Receives a command (user intent)
--   2. Loads current state via projection
--   3. Validates command against business rules
--   4. Emits events if valid (or no events if invalid)
--
-- Key Components:
--   - TransactionCommand: Sum type of all transaction commands (generated by TH)
--   - handleTransactionCommand: Command validation logic
--   - transactionCommandHandler: CommandHandler for eventium integration
--
-- Business Rules Enforced:
--   - InitiateTransfer: Source and target must be different, amount must be positive
--   - CompleteTransfer: Can only complete transactions in Pending status
--   - FailTransfer: Can only fail transactions in Pending status
--
-- All validation is pure and deterministic - same command + state → same events.
module Domain.Transaction.CommandHandler
  ( -- * Command Sum Type
    TransactionCommand (..),

    -- * Command Errors
    TransactionError (..),

    -- * Command Handler
    transactionCommandHandler,

    -- * Handler Function (exported for testing)
    handleTransactionCommand,
  )
where

import Data.List.NonEmpty (NonEmpty)
import qualified Data.List.NonEmpty as NE
import Domain.Core.Types
  ( Allocation (..),
    Allocations,
    Currency,
    Money,
    TransferKind (..),
    TransferType (..),
    allSameCurrency,
    allocationsOf,
    categorisedAmount,
    kindOf,
    moneyCurrency,
    rescaleAllocations,
    sumAllocationsUnchecked,
    unAccountId,
    unMoney,
  )
import Domain.Transaction.Commands
import Domain.Transaction.Events
import Domain.Transaction.Projection
import Eventium (CommandHandler (..))
import Eventium.TH.SumType (SumTypeTagOptions (AppendTypeNameToTags), constructSumType, defaultSumTypeOptions, withTagOptions)
