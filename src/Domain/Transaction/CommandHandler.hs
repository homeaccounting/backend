-- | The transaction command handler for eventium integration.
--
-- This combines the command handler function with the transaction projection,
-- creating a complete CommandHandler that can be registered with eventium's
-- event store.
--
-- The CommandHandler type provides:
--  - commandHandlerHandler: The validation function (handleTransactionCommand)
--  - commandHandlerProjection: How to rebuild state (transactionProjection)
--
-- Usage with eventium:
-- >>> applyCommandHandler writer reader transactionCommandHandler transactionId command
--
-- The command handler will:
--  1. Load current state via transactionProjection
--  2. Validate command via handleTransactionCommand
--  3. Store emitted events in event store
--  4. Return the events that were stored
--
-- Properties:
--  - Deterministic: Same command + state → same events
--  - Pure: No side effects in validation logic
--  - Composable: Can be combined with other command handlers
--  - State Machine: Enforces valid status transitions
--
-- Usage in Process Manager:
--  The process manager will use this command handler to issue CompleteTransactionPosting
--  and FailTransactionPosting commands based on the outcome of account operations.
transactionCommandHandler :: CommandHandler Transaction TransactionEvent TransactionCommand TransactionError
transactionCommandHandler = CommandHandler handleTransactionCommand transactionProjection
