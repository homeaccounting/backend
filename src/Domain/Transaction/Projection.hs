-- -----------------------------------------------------------------------------
-- Transaction Status
-- -----------------------------------------------------------------------------

-- | The status of a transaction in its lifecycle.
--
-- A transaction progresses through states:
--  - Pending: Transfer initiated but not yet completed
--  - Completed: Transfer successfully finished
--  - Failed: Transfer failed and cannot be completed
--
-- State Transitions:
--  Pending → Completed (via TransferCompleted event)
--  Pending → Failed (via TransferFailed event)
--
-- Terminal States: Completed and Failed are final states with no further transitions.
--
-- Invariant: Once a transaction reaches Completed or Failed, its status cannot change.
data TransactionStatus
  = -- | Transaction is in progress
    Pending
  | -- | Transaction completed successfully
    Completed
  | -- | Transaction failed with a reason
    Failed Text
  deriving (Show, Eq, Generic)

instance ToJSON TransactionStatus

instance FromJSON TransactionStatus

-- -----------------------------------------------------------------------------
-- Transaction Aggregate State
-- -----------------------------------------------------------------------------

-- | The Transaction aggregate state.
--
-- This represents the current state of a money transfer transaction, reconstructed
-- from its event history. The state is immutable and can only be changed by
-- applying events through the projection.
--
-- Fields:
--   - sourceAccountId: Source account for the transfer
--   - targetAccountId: Destination account for the transfer
--   - amount: Amount being transferred
--   - description: Description/reason for the transfer
--   - status: Current status (Pending, Completed, Failed)
--   - initiatedBy: User who initiated the transfer (for audit trail)
--
-- Invariants:
--   - Amount is always non-negative (enforced by Money type)
--   - Status transitions are unidirectional (Pending → terminal state)
--   - Source and target accounts should be different (validated at command level)
--   - State can only be modified through event handlers
--
-- State Machine:
--   Pending -[TransferCompleted]-> Completed
--   Pending -[TransferFailed]-> Failed
--
-- Example:
-- >>> let tx = Transaction sourceId targetId (Money 500.0) (Money 500.0) Nothing "Rent" Pending userId
-- >>> tx ^. #status
-- Pending
data Transaction = Transaction
  { -- | Account from which money is being debited
    sourceAccountId :: AccountId,
    -- | Account to which money is being credited
    targetAccountId :: AccountId,
    -- | Amount debited from source account
    sourceAmount :: Money,
    -- | Amount credited to target account
    targetAmount :: Money,
    -- | Exchange rate used (Nothing if same-currency)
    exchangeRate :: Maybe ExchangeRate,
    -- | Description of the transfer
    description :: Text,
    -- | Current status of the transaction
    status :: TransactionStatus,
    -- | User who initiated the transfer
    initiatedBy :: UserId,
    -- | Type of transfer (Income, Expense, Transfer)
    transferType :: TransferType,
    -- | Labels attached to this transaction (may be empty).
    labels :: Set LabelId
  }
  deriving (Show, Eq)

-- Generate optics labels for Transaction fields (accessed via #fieldName)
makeFieldLabelsNoPrefix ''Transaction

-- Derive JSON instances for Transaction (fields already unprefixed)
deriveJSON defaultOptions ''Transaction

-- | Default initial state for a Transaction aggregate.
--
-- This represents an uninitialized transaction before the TransferInitiated event
-- has been applied. It serves as the seed for the projection.
--
-- Note: In practice, this state should never be observed directly, as the
-- first event in any transaction stream should be TransferInitiated.
--
-- We use dummy values that will be overwritten by the first event:
--   - Empty UUIDs for account IDs and user ID (will be set by TransferInitiated)
--   - Zero amount (will be set by TransferInitiated)
--   - Empty description (will be set by TransferInitiated)
--   - Pending status (initial status)
transactionDefault :: Transaction
transactionDefault =
  Transaction
    { sourceAccountId = case mkAccountId nil of
        Right aid -> aid
        Left _ -> error "transactionDefault: mkAccountId should never fail for nil UUID",
      targetAccountId = case mkAccountId nil of
        Right aid -> aid
        Left _ -> error "transactionDefault: mkAccountId should never fail for nil UUID",
      sourceAmount = case mkDefaultMoney 0 of
        Right m -> m
        Left _ -> error "transactionDefault: mkDefaultMoney 0 should never fail",
      targetAmount = case mkDefaultMoney 0 of
        Right m -> m
        Left _ -> error "transactionDefault: mkDefaultMoney 0 should never fail",
      exchangeRate = Nothing,
      description = "",
      status = Pending,
      initiatedBy = unsafeUserId nil,
      transferType = Income (unsafeDictionaryEntryId nil),
      labels = Set.empty
    }

-- -----------------------------------------------------------------------------
-- Event Sum Type Construction
-- -----------------------------------------------------------------------------

-- | Generate the TransactionEvent sum type from individual event types.
--
-- This Template Haskell splice creates:
--  data TransactionEvent
--    = TransferInitiatedTransactionEvent TransferInitiated
--    | TransferCompletedTransactionEvent TransferCompleted
--    | TransferFailedTransactionEvent TransferFailed
--
-- Each variant wraps one of the individual event types defined in
-- Domain.Transaction.Events.
constructSumType
  "TransactionEvent"
  (withTagOptions AppendTypeNameToTags defaultSumTypeOptions)
  transactionEvents

-- Derive Show and Eq instances for the generated TransactionEvent type
deriving instance Show TransactionEvent

deriving instance Eq TransactionEvent

-- -----------------------------------------------------------------------------
-- Event Handlers
-- -----------------------------------------------------------------------------

-- | Handle an event and update the transaction state.
--
-- This function implements the business logic for how each event affects
-- the transaction state. It is pure and deterministic - the same event applied
-- to the same state always produces the same result.
--
-- Event Handling:
--  - TransferInitiated: Initialize transaction with accounts, amount, description, and Pending status
--  - TransferCompleted: Update status to Completed (terminal state)
--  - TransferFailed: Update status to Failed with reason (terminal state)
--
-- State Transition Rules:
--  - TransferInitiated can only be applied to default/uninitialized state
--  - TransferCompleted can only be applied to Pending transactions
--  - TransferFailed can only be applied to Pending transactions
--  - No events can modify Completed or Failed transactions (idempotent)
--
-- Mathematical Property:
--  forall e1 e2 s. handleTransactionEvent (handleTransactionEvent s e1) e2
--                   == handleTransactionEvent s (e1 <> e2)
--
-- where (<>) represents event sequencing.
--
-- Note: The function is total and handles all possible events, even if they
-- represent invalid state transitions (e.g., completing an already completed
-- transaction). In such cases, the state remains unchanged (idempotent).
handleTransactionEvent :: Transaction -> TransactionEvent -> Transaction
handleTransactionEvent transaction (TransferInitiatedTransactionEvent evt) =
  -- Initialize a new transaction with transfer details
  transaction
    & #sourceAccountId
    .~ evt.sourceAccountId
    & #targetAccountId
    .~ evt.targetAccountId
    & #sourceAmount
    .~ evt.sourceAmount
    & #targetAmount
    .~ evt.targetAmount
    & #exchangeRate
    .~ evt.exchangeRate
    & #description
    .~ evt.description
    & #status
    .~ Pending
    & #initiatedBy
    .~ evt.by
    & #transferType
    .~ evt.transferType
    & #labels
    .~ evt.labels
handleTransactionEvent transaction (TransferCompletedTransactionEvent TransferCompleted) =
  -- Mark transaction as completed
  -- Only update if currently Pending (idempotent for other states)
  case transaction ^. #status of
    Pending -> transaction & #status .~ Completed
    _ -> transaction -- Already in terminal state, no change
handleTransactionEvent transaction (TransferFailedTransactionEvent evt) =
  -- Mark transaction as failed with reason
  -- Only update if currently Pending (idempotent for other states)
  case transaction ^. #status of
    Pending -> transaction & #status .~ Failed evt.reason
    _ -> transaction -- Already in terminal state, no change
handleTransactionEvent transaction (TransactionLabelsSetTransactionEvent evt) =
  -- Replace the label set. Valid only against Completed; treated as a
  -- no-op in other states for defensive robustness — the command handler
  -- is authoritative on well-formed streams.
  case transaction ^. #status of
    Completed -> transaction & #labels .~ evt.labels
    _ -> transaction
handleTransactionEvent transaction (TransactionCategoryChangedTransactionEvent evt) =
  -- Replace the category embedded in transferType. Unreachable against
  -- Transfer because the command handler rejects such edits.
  let newTransferType = case transaction ^. #transferType of
        Income _ -> Income evt.newCategory
        Expense _ -> Expense evt.newCategory
        Transfer -> Transfer
   in transaction & #transferType .~ newTransferType

-- -----------------------------------------------------------------------------
-- Projection Definition
-- -----------------------------------------------------------------------------

-- | The transaction projection that rebuilds aggregate state from events.
--
-- This projection implements event sourcing by providing:
--  1. An initial seed state (transactionDefault)
--  2. An event handler that transitions between states
--
-- The projection can be used to:
--  - Rebuild current state from full event history
--  - Create snapshots at specific points in time
--  - Test state transitions independently
--  - Track transaction lifecycle
--
-- Usage with eventium:
-- >>> let events = [TransferInitiatedTransactionEvent (TransferInitiated sourceId targetId (Money 500.0) "Rent")]
-- >>> latestProjection transactionProjection events
-- Transaction {sourceAccountId = sourceId, ..., status = Pending}
--
-- Mathematical Properties:
--  - Identity: latestProjection p [] == projectionSeed p
--  - Composition: latestProjection p (e1 ++ e2) ==
--                 latestProjection p [e1, e2] (applied sequentially)
--  - Status monotonicity: Status transitions are irreversible
--    (Pending → terminal state only)
transactionProjection :: Projection Transaction TransactionEvent
transactionProjection = Projection transactionDefault handleTransactionEvent
