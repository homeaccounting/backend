-- |
-- Module      : Domain.Transaction.Projection
-- Description : Projection for rebuilding Transaction aggregate state from events
--
-- This module defines the Transaction aggregate state and how it is reconstructed
-- from the event stream. The projection implements event sourcing by folding
-- events over an initial state to produce the current state.
--
-- Key Components:
--   - Transaction: The aggregate state containing transfer details and status
--   - TransactionEvent: Sum type of all possible transaction events (generated by TH)
--   - transactionProjection: The projection that rebuilds state from events
--
-- The projection is the core of event sourcing - it ensures that the current
-- state can always be reconstructed by replaying the event history.
--
-- Mathematical Properties:
--   - Deterministic: Same events always produce same state
--   - Associative: Order of event application matters
--   - Idempotent event handlers: Replaying same events produces same result
--   - Status transitions: Pending → Completed | Failed (terminal states)
module Domain.Transaction.Projection
  ( -- * Transaction Aggregate
    Transaction (..),

    -- * Transaction Status
    TransactionStatus (..),
    StatusKind (..),
    statusKind,
    parseStatusKind,
    renderStatusKind,

    -- * Optics Labels (via OverloadedLabels)
    -- $labels

    -- * Event Sum Type
    TransactionEvent (..),

    -- * Projection
    transactionProjection,

    -- * Helper Functions
    transactionDefault,
  )
where

