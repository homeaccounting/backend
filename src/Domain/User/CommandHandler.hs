{-# LANGUAGE RecordWildCards #-}
{-# LANGUAGE TemplateHaskell #-}

-- |
-- Module      : Domain.User.CommandHandler
-- Description : Command handler for the User aggregate
--
-- This module implements the command handler that validates user commands
-- against the current aggregate state and emits appropriate events.
--
-- The command handler is the core of the write side in CQRS:
--   1. Receives a command (user intent)
--   2. Loads current state via projection
--   3. Validates command against business rules
--   4. Emits events if valid (or no events if invalid)
--
-- Key Components:
--   - UserCommand: Sum type of all user commands (generated by TH)
--   - handleUserCommand: Command validation logic
--   - userCommandHandler: CommandHandler for eventium integration
--
-- Business Rules Enforced:
--   - RegisterUser: Cannot register if user already exists
--   - RegisterViaTelegram: Cannot register if user already exists
--   - LinkOAuthAccount: User must exist, OAuth not already linked
--   - LinkTelegramAccount: User must exist, Telegram not already linked
--   - UnlinkOAuthAccount: User must exist, must have other login methods
--   - UnlinkTelegramAccount: User must exist, must have other login methods
--   - ChangePassword: User must exist
--
-- All validation is pure and deterministic - same command + state = same events.
module Domain.User.CommandHandler
  ( -- * Command Sum Type
    UserCommand (..),

    -- * Command Errors
    UserError (..),

    -- * Command Handler
    userCommandHandler,

    -- * Handler Function (exported for testing)
    handleUserCommand,
  )
where

import Domain.Core.Types
  ( OAuthIdentity (..),
  )
import Domain.User.Commands
import Domain.User.Events
import Domain.User.Projection
import Eventium (CommandHandler (..))
import Eventium.TH.SumType (SumTypeTagOptions (AppendTypeNameToTags), constructSumType, defaultSumTypeOptions, withTagOptions)
import Optics ((^.))

-- -----------------------------------------------------------------------------
-- Command Errors
-- -----------------------------------------------------------------------------

-- | Errors that can occur when handling user commands.
data UserError
  = UserAlreadyRegistered
  | UserNotRegistered
  | OAuthAlreadyLinked
  | TelegramAlreadyLinked
  | CannotRemoveLastLoginMethod
  | OAuthNotLinked
  | TelegramNotLinked
  deriving (Show, Eq)

-- -----------------------------------------------------------------------------
-- Command Sum Type Construction
-- -----------------------------------------------------------------------------

-- | Generate the UserCommand sum type from individual command types.
--
-- This Template Haskell splice creates:
--   data UserCommand
--     = RegisterUserUserCommand RegisterUser
--     | RegisterViaTelegramUserCommand RegisterViaTelegram
--     | LinkOAuthAccountUserCommand LinkOAuthAccount
--     | LinkTelegramAccountUserCommand LinkTelegramAccount
--     | UnlinkOAuthAccountUserCommand UnlinkOAuthAccount
--     | UnlinkTelegramAccountUserCommand UnlinkTelegramAccount
--     | ChangePasswordUserCommand ChangePassword
--
-- Each variant wraps one of the individual command types defined in
-- Domain.User.Commands.
constructSumType
  "UserCommand"
  (withTagOptions AppendTypeNameToTags defaultSumTypeOptions)
  userCommands

-- -----------------------------------------------------------------------------
-- Command Handler Function
-- -----------------------------------------------------------------------------

-- | Handle a user command and produce events.
--
-- This function implements the business logic for validating commands against
-- the current aggregate state. It is pure and deterministic.
--
-- Command Handling:
--   - RegisterUser: Validates user doesn't exist, creates user
--   - RegisterViaTelegram: Validates user doesn't exist, creates user
--   - LinkOAuthAccount: Validates user exists and OAuth not already linked
--   - LinkTelegramAccount: Validates user exists and Telegram not already linked
--   - UnlinkOAuthAccount: Validates user exists and has other login methods
--   - UnlinkTelegramAccount: Validates user exists and has other login methods
--   - ChangePassword: Validates user exists
--
-- Returns:
--   @'Right' events@ on success, @'Left' error@ on rejection.
--
-- Note: Email/Telegram uniqueness across users must be validated at the API layer
-- using read models, as the aggregate only has access to its own state.
handleUserCommand :: User -> UserCommand -> Either UserError [UserEvent]
-- Handle RegisterUser command
handleUserCommand user (RegisterUserUserCommand RegisterUser {..})
  | user ^. #isRegistered = Left UserAlreadyRegistered
  | otherwise =
      Right
        [ UserRegisteredUserEvent
            UserRegistered
              { email = email,
                passwordHash = passwordHash,
                externalAccountId = externalAccountId
              }
        ]
-- Handle RegisterViaTelegram command
handleUserCommand user (RegisterViaTelegramUserCommand RegisterViaTelegram {..})
  | user ^. #isRegistered = Left UserAlreadyRegistered
  | otherwise =
      Right
        [ UserRegisteredViaTelegramUserEvent
            UserRegisteredViaTelegram
              { identity = identity,
                externalAccountId = externalAccountId
              }
        ]
-- Handle LinkOAuthAccount command
handleUserCommand user (LinkOAuthAccountUserCommand LinkOAuthAccount {..})
  | not (user ^. #isRegistered) = Left UserNotRegistered
  | hasOAuthProvider identity.provider (user ^. #oauthIdentities) = Left OAuthAlreadyLinked
  | otherwise =
      Right
        [ OAuthAccountLinkedUserEvent
            OAuthAccountLinked
              { identity = identity
              }
        ]
  where
    hasOAuthProvider theProvider =
      any (\i -> i.provider == theProvider)
-- Handle LinkTelegramAccount command
handleUserCommand user (LinkTelegramAccountUserCommand LinkTelegramAccount {..})
  | not (user ^. #isRegistered) = Left UserNotRegistered
  | Just _ <- user ^. #telegramIdentity = Left TelegramAlreadyLinked
  | otherwise =
      Right
        [ TelegramAccountLinkedUserEvent
            TelegramAccountLinked
              { identity = identity
              }
        ]
-- Handle UnlinkOAuthAccount command
handleUserCommand user (UnlinkOAuthAccountUserCommand UnlinkOAuthAccount {..})
  | not (user ^. #isRegistered) = Left UserNotRegistered
  | loginMethodCount user <= 1 = Left CannotRemoveLastLoginMethod
  | not (hasOAuthIdentity identity (user ^. #oauthIdentities)) = Left OAuthNotLinked
  | otherwise =
      Right
        [ OAuthAccountUnlinkedUserEvent
            OAuthAccountUnlinked
              { identity = identity
              }
        ]
  where
    hasOAuthIdentity target =
      any
        ( \i ->
            i.provider == target.provider
              && i.subject == target.subject
        )
-- Handle UnlinkTelegramAccount command
handleUserCommand user (UnlinkTelegramAccountUserCommand UnlinkTelegramAccount)
  | not (user ^. #isRegistered) = Left UserNotRegistered
  | loginMethodCount user <= 1 = Left CannotRemoveLastLoginMethod
  | Nothing <- user ^. #telegramIdentity = Left TelegramNotLinked
  | otherwise =
      Right [TelegramAccountUnlinkedUserEvent TelegramAccountUnlinked]
-- Handle ChangePassword command
handleUserCommand user (ChangePasswordUserCommand ChangePassword {..})
  | not (user ^. #isRegistered) = Left UserNotRegistered
  | otherwise =
      Right
        [ PasswordChangedUserEvent
            PasswordChanged
              { newHash = newHash
              }
        ]

-- -----------------------------------------------------------------------------
-- Command Handler
-- -----------------------------------------------------------------------------

-- | The user command handler for eventium integration.
--
-- This combines the command handler function with the user projection,
-- creating a complete CommandHandler that can be registered with eventium's
-- event store.
--
-- The CommandHandler type provides:
--   - commandHandlerHandler: The validation function (handleUserCommand)
--   - commandHandlerProjection: How to rebuild state (userProjection)
--
-- Usage with eventium:
-- >>> applyCommandHandler writer reader userCommandHandler userId command
--
-- The command handler will:
--   1. Load current state via userProjection
--   2. Validate command via handleUserCommand
--   3. Store emitted events in event store
--   4. Return the events that were stored
--
-- Properties:
--   - Deterministic: Same command + state = same events
--   - Pure: No side effects in validation logic
--   - Composable: Can be combined with other command handlers
userCommandHandler :: CommandHandler User UserEvent UserCommand UserError
userCommandHandler = CommandHandler handleUserCommand userProjection
